# Counts across all tenants for GET /metrics (Prometheus). Numbers only, no tenant data.
MONITORING_SQL = """
    CREATE FUNCTION platform_monitoring()
    RETURNS TABLE (metric text, label text, value bigint)
    LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
    AS $$
        SELECT 'edge_devices', status, count(*) FROM edge_devices
            WHERE status <> 'retired' GROUP BY status
        UNION ALL SELECT 'cameras', health, count(*) FROM cameras WHERE enabled GROUP BY health
        UNION ALL SELECT 'incidents_open', kind, count(*) FROM health_incidents
            WHERE resolved_at IS NULL GROUP BY kind
        UNION ALL SELECT 'alert_deliveries_queued', '', count(*) FROM alert_deliveries
            WHERE status = 'queued'
        UNION ALL SELECT 'webhook_deliveries_queued', '', count(*) FROM webhook_deliveries
            WHERE status = 'queued'
        UNION ALL SELECT 'tenants', status, count(*) FROM tenants GROUP BY status
    $$
"""


