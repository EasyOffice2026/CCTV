def lang(locale: str | None) -> str:
    return locale if locale in (Locale.EN.value, Locale.AR.value) else Locale.EN.value


def t(locale: str | None, key: str, **values: object) -> str:
    language = lang(locale)
    template = TEXT[language].get(key) or TEXT["en"].get(key, key)
    return template.format(**values) if values else template


def event_label(locale: str | None, event_type: str) -> str:
    language = lang(locale)
    return EVENT_TYPES[language].get(event_type) or EVENT_TYPES["en"].get(event_type, event_type)
